import { test, expect } from '@playwright/test';
const errors=[];
test.describe.configure({mode:'serial'});
test.beforeEach(async({page})=>{page.on('pageerror',e=>errors.push(e.message));await page.goto('/');});
test('member submits documents, edits pending claim, pays and downloads receipt',async({page})=>{
  await page.screenshot({path:'test-results/sign-in.png',fullPage:true});
  await page.getByRole('button',{name:'Member',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Good /})).toBeVisible();
  await expect(page.getByText('Demo workspace · Synthetic data')).toBeVisible();
  await page.locator('.chart-container path.recharts-area-curve').first().waitFor();
  await page.waitForTimeout(1700);
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'New claim',exact:true}).click();
  await page.getByLabel('Policy',{exact:true}).selectOption({index:1});
  await page.getByLabel('Patient’s age').fill('32');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByLabel('Treatment / condition').fill('Browser QA care assessment');
  await page.getByLabel('Hospital name').fill('CareClaim Sample Hospital');
  await page.getByLabel('Admission date').fill('2026-11-01');
  await page.getByLabel('Discharge date').fill('2026-11-02');
  await page.getByLabel('Claim amount (₹)').fill('1250');
  await page.locator('input[type=file]').setInputFiles({name:'sample-bill.pdf',mimeType:'application/pdf',buffer:Buffer.from('%PDF-1.4\n1 0 obj<</Type/Catalog>>endobj\n%%EOF')});
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Submit claim',exact:true}).click();
  await expect(page.getByText('Browser QA care assessment',{exact:true})).toBeVisible();
  await page.getByText('Browser QA care assessment',{exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your claim journey'})).toBeVisible();
  const doc=page.getByRole('button',{name:/sample-bill.pdf/});
  const download=page.waitForEvent('download');await doc.click();expect((await download).suggestedFilename()).toBe('sample-bill.pdf');
  await page.getByRole('button',{name:'Edit pending claim'}).click();
  await page.getByLabel('Amount (₹)',{exact:true}).fill('1350');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(page.getByText('₹1,350',{exact:true}).first()).toBeVisible();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByRole('link',{name:'Payments',exact:true}).click();
  await page.getByRole('button',{name:/Pay premium/}).first().click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:/Continue to payment/}).click();
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByText('Sandbox payment complete. Your demo receipt is ready.')).toBeVisible();
  const receipt=page.waitForEvent('download');await page.getByRole('button',{name:/Download receipt/}).first().click();expect((await receipt).suggestedFilename()).toMatch(/\.txt$/);
  await page.getByRole('link',{name:'Insights & reports'}).click();
  await expect(page.getByRole('heading',{name:'Claim amount by patient'})).toBeVisible();
  await page.getByRole('link',{name:/Care corner/}).click();
  await expect(page.locator('video')).toBeVisible();
  await expect(page.locator('video')).toHaveJSProperty('readyState',4);
  expect(await page.locator('video').evaluate(v=>v.duration)).toBe(16);
  await page.getByRole('link',{name:/Aarav Sharma/}).click();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
});
test('reviewer approves submitted claim and sees its audit record',async({page})=>{
  await page.getByRole('button',{name:'Claim officer',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Good /})).toBeVisible();
  await expect(page.getByRole('button',{name:'New claim',exact:true})).toHaveCount(0);
  await page.getByRole('link',{name:/All claims/}).click();
  await page.getByLabel('Filter claims').fill('Browser QA care assessment');
  await page.getByText('Browser QA care assessment',{exact:true}).first().click();
  await page.getByLabel('Decision').selectOption('Approved');
  await page.getByLabel('Review note').fill('Sample medical bill verified during browser acceptance check.');
  await page.getByRole('button',{name:'Save decision'}).click();
  await expect(page.getByRole('button',{name:'Save decision'})).toBeDisabled();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByRole('link',{name:'Activity log'}).click();
  await expect(page.getByText('Sample medical bill verified during browser acceptance check.')).toBeVisible();
  await page.getByRole('link',{name:'Payments',exact:true}).click();
  await expect(page.getByRole('button',{name:/Pay premium/})).toHaveCount(0);
  expect(errors).toEqual([]);
});
test('mobile layout stays within viewport and navigation works',async({page})=>{
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Member',exact:true}).click();
  await expect(page.getByRole('heading',{name:/Good /})).toBeVisible();
  await page.waitForTimeout(1700);
  await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.getByRole('button',{name:'Open menu'}).click();
  await page.getByRole('link',{name:/My claims/}).click();
  await expect(page.getByRole('heading',{name:'Your claims. Less uncertainty.'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
});
test('standalone browser preview supports persistent claims and sandbox payments',async({page})=>{
  await page.route('**/api/health',route=>route.abort());
  await page.reload();
  await page.getByRole('button',{name:'Member',exact:true}).click();
  await expect(page.getByText('Interactive preview · Sample data saved in this browser')).toBeVisible();
  await page.getByRole('link',{name:'Payments',exact:true}).click();
  await page.getByRole('button',{name:/Pay premium/}).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button',{name:/Continue to payment/}).click();
  await expect(page.getByText('Sandbox payment complete. Your demo receipt is ready.')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('button',{name:/Up to date/})).toBeDisabled();
  expect(errors).toEqual([]);
});
